/*
Назначение: генератор исходного Go-файла alphabet.go для пакета base58.
Он создает таблицу b58 размером 256 элементов, позволяющую быстро
определять индекс каждого возможного байта в алфавите Base58 Bitcoin.
Для каждого значения byte от 0 до 255 выполняется поиск в alphabet58.
Если байт найден, в таблицу записывается его индекс от 0 до 57.
Если байт отсутствует, записывается 255, обозначающий недопустимый
символ. Таблица разбивается на строки по 8 значений для читаемости.

generateAlphabetTable отвечает за генерацию содержимого и проверяет
ошибки каждой операции записи. bufio.Writer накапливает мелкие записи
в буфере и отправляет их в файл при заполнении буфера или вызове Flush.
run создает alphabet.go, запускает генерацию и проверяет ошибки закрытия.
Оборачивание ошибок через %w сохраняет исходную причину ошибки для
последующей диагностики. main выводит ошибку в stderr и завершает
процесс с ненулевым кодом, если генерация не удалась.

Файл alphabet.go является генерируемым артефактом, поэтому его не следует
редактировать вручную. Директива go:build ignore исключает этот файл
генератора из обычной сборки пакета. Генератор запускается отдельно:
go run genalphabet.go.

Важно: генератор сохраняет формат таблицы и алгоритм исходного кода.
При этом запись выполняется буферизированно, а ошибки записи, сброса
буфера и закрытия файла обрабатываются явно.
*/

 package main

 import (
 	"bufio"
 	"bytes"
 	"fmt"
 	"os"
 	"strconv"
 )

 const (
 	outputFile = "alphabet.go"
 	alphabet58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"
 	invalidIdx = 255
 	rowSize    = 8
 	tableSize  = 256
 )

 var (
 	start = []byte(`// Copyright (c) 2015 The btcsuite developers
 // Use of this source code is governed by an ISC
 // license that can be found in the LICENSE file.

 // AUTOGENERATED by genalphabet.go; do not edit.

 package base58

 const (
 	// alphabet is the modified base58 alphabet used by Bitcoin.
 	alphabet = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"

 	alphabetIdx0 = '1'
 )

 var b58 = [256]byte{`)

 	end = []byte("}")
 )

 func generateAlphabetTable(dst *bufio.Writer) error {
 	alphabet := []byte(alphabet58)

 	if _, err := dst.Write(start); err != nil {
 		return fmt.Errorf("write generated file header: %w", err)
 	}

 	if err := dst.WriteByte('\n'); err != nil {
 		return fmt.Errorf("write header newline: %w", err)
 	}

 	var valueBuffer [3]byte

 	for row := 0; row < tableSize/rowSize; row++ {
 		if err := dst.WriteByte('\t'); err != nil {
 			return fmt.Errorf("write row indentation: %w", err)
 		}

 		for col := 0; col < rowSize; col++ {
 			value := byte(row*rowSize + col)
 			index := bytes.IndexByte(alphabet, value)

 			if index < 0 {
 				valueBuffer = [3]byte{'2', '5', '5'}
 			} else {
 				encoded := strconv.AppendInt(nil, int64(index), 10)
 				if _, err := dst.Write(encoded); err != nil {
 					return fmt.Errorf("write index for byte %d: %w", value, err)
 				}
 				goto separator
 			}

 			if _, err := dst.Write(valueBuffer[:]); err != nil {
 				return fmt.Errorf("write invalid index for byte %d: %w", value, err)
 			}

 		separator:
 			if err := dst.WriteByte(','); err != nil {
 				return fmt.Errorf("write table separator: %w", err)
 			}

 			if col != rowSize-1 {
 				if err := dst.WriteByte(' '); err != nil {
 					return fmt.Errorf("write table spacing: %w", err)
 				}
 			}
 		}

 		if err := dst.WriteByte('\n'); err != nil {
 			return fmt.Errorf("write table newline: %w", err)
 		}
 	}

 	if _, err := dst.Write(end); err != nil {
 		return fmt.Errorf("write generated file footer: %w", err)
 	}

 	if err := dst.WriteByte('\n'); err != nil {
 		return fmt.Errorf("write final newline: %w", err)
 	}

 	return dst.Flush()
 }

 func run() (err error) {
 	file, err := os.Create(outputFile)
 	if err != nil {
 		return fmt.Errorf("create %s: %w", outputFile, err)
 	}

 	defer func() {
 		if closeErr := file.Close(); closeErr != nil && err == nil {
 			err = fmt.Errorf("close %s: %w", outputFile, closeErr)
 		}
 	}()

 	writer := bufio.NewWriter(file)

 	if err := generateAlphabetTable(writer); err != nil {
 		return fmt.Errorf("generate alphabet table: %w", err)
 	}

 	return nil
 }

 func main() {
 	if err := run(); err != nil {
 		fmt.Fprintln(os.Stderr, "genalphabet:", err)
 		os.Exit(1)
 	}
 }
